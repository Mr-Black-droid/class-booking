#!/usr/bin/env node
// Reads .env and produces everything that depends on it:
//   web/config.js                          public settings for the web page
//   supabase/generated/seed.sql            who may get in, who is admin, time zone
//   supabase/generated/notify-trigger.sql  connects the database to the email function
//   supabase/generated/secrets.env         secrets for the email function
// Nothing is sent anywhere. You paste the SQL files into the Supabase SQL editor.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const envPath = path.join(root, '.env');
if (!fs.existsSync(envPath)) {
  console.error('No .env file found. Copy .env.example to .env and fill it in first.');
  process.exit(1);
}

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i < 0) continue;
    let v = line.slice(i + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    out[line.slice(0, i).trim()] = v;
  }
  return out;
}

let text = fs.readFileSync(envPath, 'utf8');
const env = parseEnv(text);

if (!env.NOTIFY_SECRET) {
  env.NOTIFY_SECRET = crypto.randomBytes(24).toString('hex');
  text = /^NOTIFY_SECRET=.*$/m.test(text)
    ? text.replace(/^NOTIFY_SECRET=.*$/m, `NOTIFY_SECRET=${env.NOTIFY_SECRET}`)
    : text + `\nNOTIFY_SECRET=${env.NOTIFY_SECRET}\n`;
  fs.writeFileSync(envPath, text);
  console.log('Generated NOTIFY_SECRET and saved it in .env');
}

const problems = [];
const need = (k) => { if (!env[k]) problems.push(`${k} is empty`); };
['ADMIN_EMAILS', 'SUPABASE_URL', 'SUPABASE_ANON_KEY', 'TIMEZONE', 'APP_URL', 'RESEND_API_KEY', 'MAIL_FROM'].forEach(need);
for (const [k, v] of Object.entries(env)) if (/CHANGE-ME/i.test(v)) problems.push(`${k} still contains the CHANGE-ME placeholder`);

const list = (s) => (s || '').split(',').map((x) => x.trim().toLowerCase()).filter(Boolean);
const admins = [...new Set(list(env.ADMIN_EMAILS))];
const staff = [...new Set(list(env.STAFF_EMAILS))].filter((e) => !admins.includes(e));
const emailRe = /^[^@\s'";]+@[^@\s'";]+\.[^@\s'";]+$/;
for (const e of [...admins, ...staff]) if (!emailRe.test(e)) problems.push(`"${e}" is not a valid email address`);
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/i.test(env.SUPABASE_URL || '') && !/CHANGE-ME/i.test(env.SUPABASE_URL || '')) problems.push('SUPABASE_URL should look like https://xxxx.supabase.co');
try { new Intl.DateTimeFormat('en', { timeZone: env.TIMEZONE }); } catch { problems.push(`TIMEZONE "${env.TIMEZONE}" is not a valid time zone name`); }

if (problems.length) {
  console.error('\nSetup stopped. Fix these in .env, then run this again:\n');
  problems.forEach((p) => console.error('  - ' + p));
  process.exit(1);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const base = env.SUPABASE_URL.replace(/\/$/, '');
const gen = path.join(root, 'supabase', 'generated');
fs.mkdirSync(gen, { recursive: true });

// 1. public web config
const cfg = {
  SUPABASE_URL: base, SUPABASE_ANON_KEY: env.SUPABASE_ANON_KEY, TIMEZONE: env.TIMEZONE,
  APP_NAME: env.APP_NAME || 'Class slot booking', GOOGLE_HD: env.GOOGLE_HD || '',
};
fs.writeFileSync(path.join(root, 'web', 'config.js'),
  '// Generated by scripts/setup.mjs from .env. Public by design: the anon key only works inside the\n' +
  "// database's access rules. Never put the service-role key or any password in this file.\n" +
  'window.APP_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n');

// 2. who may get in
const rows = [
  ...admins.map((e) => `  (${q(e)}, true)`),
  ...staff.map((e) => `  (${q(e)}, false)`),
].join(',\n');
fs.writeFileSync(path.join(gen, 'seed.sql'),
`-- Generated by scripts/setup.mjs. Paste into the Supabase SQL editor and run.
-- Safe to run again after editing .env: it makes the admin list match .env exactly.

update public.settings set value = ${q(env.TIMEZONE)} where key = 'timezone';

insert into public.allowed_users (email, is_admin) values
${rows}
on conflict (email) do update set is_admin = excluded.is_admin;

-- Only the emails in ADMIN_EMAILS are admins. Anyone else loses admin rights.
update public.allowed_users set is_admin = false
 where is_admin and email <> all (array[${admins.map(q).join(', ')}]);
`);

// 3. database -> email function
fs.writeFileSync(path.join(gen, 'notify-trigger.sql'),
`-- Generated by scripts/setup.mjs. Paste into the Supabase SQL editor and run, AFTER the email
-- function has been deployed (README step 6). Contains a secret: do not share or commit.

create extension if not exists pg_net with schema extensions;

create or replace function public.notify_outbox() returns trigger
language plpgsql security definer set search_path = public, extensions, net as $$
begin
  perform net.http_post(
    url     := ${q(base + '/functions/v1/notify')},
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-notify-secret', ${q(env.NOTIFY_SECRET)}),
    body    := jsonb_build_object('record', to_jsonb(new))
  );
  return new;
end $$;
revoke execute on function public.notify_outbox() from public, anon, authenticated;

drop trigger if exists outbox_notify on public.outbox;
create trigger outbox_notify after insert on public.outbox
  for each row execute function public.notify_outbox();
`);

// 4. secrets for the email function
fs.writeFileSync(path.join(gen, 'secrets.env'),
[`NOTIFY_SECRET=${env.NOTIFY_SECRET}`, `RESEND_API_KEY=${env.RESEND_API_KEY}`, `MAIL_FROM=${env.MAIL_FROM}`,
 `APP_URL=${env.APP_URL}`, `NOTIFY_ALL_BOOKINGS=${env.NOTIFY_ALL_BOOKINGS || 'false'}`].join('\n') + '\n');

console.log(`
Done.
  Admins (${admins.length}): ${admins.join(', ')}
  Staff  (${staff.length}): ${staff.join(', ') || '(none yet, add them in the People tab)'}

Written:
  web/config.js
  supabase/generated/seed.sql
  supabase/generated/notify-trigger.sql
  supabase/generated/secrets.env

Next: follow README.md from step 4.`);
