// Turns the placeholder emails in .env into SQL you paste into the Supabase SQL editor.
// Usage: node scripts/make-seed.mjs   (writes supabase/seed.generated.sql)
import { writeFileSync } from 'node:fs';
import { loadEnv } from './env.mjs';

const env = loadEnv();
const emailRe = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const admins = [
  ['ADMIN_EMAIL_BOSS', 'Boss'],
  ['ADMIN_EMAIL_DEVELOPER', 'Developer'],
  ['ADMIN_EMAIL_HOD', 'Head of Department'],
].map(([key, label]) => ({ key, label, email: (env[key] || '').trim().toLowerCase() }));

const problems = admins.filter((a) => !emailRe.test(a.email) || /@example\.com$/.test(a.email) || a.email.includes('your-'));
if (problems.length) {
  console.error('These are missing or still placeholders in .env: ' + problems.map((p) => p.key).join(', '));
  process.exit(1);
}
const staff = (env.STAFF_EMAILS || '').split(',').map((s) => s.trim().toLowerCase()).filter(Boolean);
const badStaff = staff.filter((e) => !emailRe.test(e));
if (badStaff.length) {
  console.error('Not valid email addresses in STAFF_EMAILS: ' + badStaff.join(', '));
  process.exit(1);
}
const adminSet = new Set(admins.map((a) => a.email));
if (adminSet.size !== admins.length) {
  console.error('The three admin emails must be different from each other.');
  process.exit(1);
}

const lines = ['-- Generated by scripts/make-seed.mjs. Paste into the Supabase SQL editor and run.'];
lines.push('insert into public.allowed_users (email, role, display_name) values');
const rows = admins.map((a) => `  (${q(a.email)}, 'admin', ${q(a.label)})`);
for (const e of staff) if (!adminSet.has(e)) rows.push(`  (${q(e)}, 'staff', null)`);
lines.push(rows.join(',\n'));
lines.push("on conflict (email) do update set role = excluded.role;");
lines.push('');
const setting = (k, v) => `update public.app_settings set value = ${q(v)} where key = ${q(k)};`;
if (env.TIMEZONE) lines.push(setting('timezone', env.TIMEZONE));
if (env.SITE_URL && !env.SITE_URL.includes('YOUR-')) lines.push(setting('site_url', env.SITE_URL));
lines.push(setting('notify_every_booking', env.NOTIFY_EVERY_BOOKING === 'true' ? 'true' : 'false'));
writeFileSync('supabase/seed.generated.sql', lines.join('\n') + '\n');
console.log(`Wrote supabase/seed.generated.sql with ${admins.length} admins and ${staff.length} staff.`);
